#PROGRAM TO FIND THE HEIGHT OF A TRIANGLE USING SINE FUNCTION
import math
h1=16
h2=20
h3=24
d1=75
d2=0
d3=45
d4=80
a=(math.sin(d1))*h1
b=(math.sin(d2))*h2
c=(math.sin(d3))*h3
d=(math.sin(d4))*h3
print("when the angle is 75 degree and the length is 16 then the height is:",a)
print("when the angle is 0 degree and the length is 20 then the height is:",b)
print("when the angle is 45 degree and the length is 24 then the height is:",c)
print("when the angle is 80 degree and the length is 24 then the height is:",d)